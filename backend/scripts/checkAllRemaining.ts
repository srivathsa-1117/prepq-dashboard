async function main() {
  const token = process.env.META_SYSTEM_USER_ACCESS_TOKEN;
  if (!token) throw new Error('no token');
  const client = new MetaClient(token, 'act_1892794114540071');

  console.log('total ids to check:', ids.length);
  const raw = await client.fetchCreativesByIds(ids);
  console.log('raw creatives returned:', raw.length);

  const normalized = raw.map(transformCreative);
  const withImages = normalized.filter((c) => c.carouselImageHashes.length > 0);
  const withVideo = normalized.filter((c) => c.videoId);
  const withNeither = normalized.filter((c) => c.carouselImageHashes.length === 0 && !c.videoId && !c.imageUrl);

  console.log('with resolvable image hashes:', withImages.length);
  console.log('with a video_id:', withVideo.length);
  console.log('with NEITHER (dead end):', withNeither.length);
  console.log('sample dead-end raw:', JSON.stringify(withNeither.slice(0, 3).map((c) => c.raw), null, 2));
}

main()
